#!/usr/bin/env python3
"""Generates src/frontend/DialogFont.h: an 8x16 anti-aliased bitmap font (code points 32-255)
rasterised from DejaVu Sans Mono (Bitstream Vera / DejaVu licence, which permits embedding and
redistribution; see the header comment). 4 bits of coverage per pixel.

usage: make_font.py [path/to/DejaVuSansMono.ttf]"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H = 8, 16
font = ImageFont.truetype(ttf, 13)
ascent, _ = font.getmetrics()
rows = []
for cp in range(32, 256):
    img = Image.new("L", (W, H), 0)
    ch = chr(cp)
    if cp < 127 or cp >= 160:
        ImageDraw.Draw(img).text((0, 13 - ascent), ch, font=font, fill=255)
    px = list(img.getdata())
    nib = [(p + 8) // 17 for p in px]  # 0..15
    data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    rows.append(data)

out = ["// Generated by tools/font/make_font.py from DejaVu Sans Mono. Do not edit.",
       "// DejaVu fonts: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera); DejaVu changes are in",
       "// the public domain. The Bitstream Vera licence permits embedding and redistribution.",
       "#pragma once",
       "#include <cstdint>",
       "",
       "namespace ca::font {",
       "constexpr int kW = %d, kH = %d, kFirst = 32, kLast = 255;" % (W, H),
       "// Per glyph kW*kH/2 bytes, row-major, two 4-bit coverages per byte (high nibble first).",
       "const uint8_t kGlyphs[] = {"]
for cp, data in zip(range(32, 256), rows):
    out.append("    " + ", ".join("0x%02x" % b for b in data) + ",  // %d" % cp)
out += ["};", "} // namespace ca::font", ""]
open(sys.argv[2] if len(sys.argv) > 2 else "src/frontend/DialogFont.h", "w").write("\n".join(out))
