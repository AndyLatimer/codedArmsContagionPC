#!/usr/bin/env python3
"""Builds the imports table of a game (lib, nid, name, return, args) and src/psp/hle_nids.cpp.

Names and signatures come from the HLE function tables of a PPSSPP source checkout
({0xNID, &Wrap..., "name", 'r', "args"} entries in Core/HLE). NIDs PPSSPP does not know
(e.g. the game's own modules) keep an empty name and are reported.

Usage:
  gen_imports.py --iso GAME.iso --ppsspp PPSSPP_DIR --tsv OUT.tsv --cpp src/psp/hle_nids.cpp [--extra other.tsv ...]
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from iso9660 import read_iso_file  # noqa: E402
from pspelf import PspModule  # noqa: E402

ENTRY = re.compile(r'\{\s*0[xX]([0-9A-Fa-f]{8})\s*,[^{}"]*"([A-Za-z_0-9]+)"\s*(?:,\s*\'(.)\'\s*,\s*"([^"]*)")?')


def ppsspp_db(root):
    db = {}
    for path in glob.glob(os.path.join(root, "Core", "HLE", "*.cpp")):
        for m in ENTRY.finditer(open(path, encoding="utf-8", errors="replace").read()):
            db.setdefault(m.group(1).lower(), (m.group(2), m.group(3) or "", m.group(4) or ""))
    return db


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--iso")
    ap.add_argument("--elf", action="append", default=[], help="additional (or instead of --iso) PRX files")
    ap.add_argument("--ppsspp", required=True)
    ap.add_argument("--tsv", required=True)
    ap.add_argument("--cpp")
    ap.add_argument("--extra", action="append", default=[], help="tsv with names for NIDs PPSSPP lacks")
    a = ap.parse_args()

    db = ppsspp_db(a.ppsspp)
    for path in a.extra:
        for line in open(path, encoding="utf-8"):
            if line.startswith("#") or not line.strip():
                continue
            c = line.rstrip("\n").split("\t")
            if len(c) >= 3 and c[2]:
                db[c[1].lower()] = (c[2], c[3] if len(c) > 3 else "", c[4] if len(c) > 4 else "")
    mods = []
    if a.iso:
        mods.append(PspModule(read_iso_file(a.iso, "PSP_GAME/SYSDIR/BOOT.BIN")))
    mods += [PspModule(open(p, "rb").read()) for p in a.elf]
    rows, seen = [], set()
    for mod in mods:
        for s in mod.stubs:
            nid = "%08x" % s.nid
            if nid in seen:
                continue
            seen.add(nid)
            name, ret, args = db.get(nid, ("", "", ""))
            rows.append((s.lib, nid, name, ret, args))
    with open(a.tsv, "w", encoding="utf-8") as f:
        f.write("# library\tnid\tname\treturn\targs (PPSSPP signature notation); generated by gen_imports.py\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    unknown = [r for r in rows if not r[2]]
    print("imports: %d, named: %d, unknown: %d" % (len(rows), len(rows) - len(unknown), len(unknown)))
    for r in unknown:
        print("  unknown %s %s" % (r[0], r[1]))
    if a.cpp:
        with open(a.cpp, "w", encoding="utf-8") as f:
            f.write("// NID -> function name for the imports of the game (generated by tools/recomp/gen_imports.py\n"
                    "// from the HLE tables of PPSSPP). Unknown NIDs fall back to \"<library>_<nid>\".\n"
                    "#include <cstdint>\n\nnamespace psp::kernel {\n\nconst char* nidName(uint32_t nid) {\n    switch (nid) {\n")
            for r in rows:
                if r[2]:
                    f.write("    case 0x%su: return \"%s\";\n" % (r[1], r[2]))
            f.write("    default: return nullptr;\n    }\n}\n\n}  // namespace psp::kernel\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
