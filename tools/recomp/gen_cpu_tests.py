#!/usr/bin/env python3
"""Generates the differential CPU test cases: one C function per distinct non-control,
non-VFPU instruction word found in the game's code, using the real code generator, plus a
table pairing each with the PPSSPP interpreter handler that implements it.

Usage: gen_cpu_tests.py BOOT.BIN OUT.c
The output is derived from the game and stays in the build directory.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codegen  # noqa: E402
import functions  # noqa: E402
from allegrex import decode  # noqa: E402
from pspelf import PspModule  # noqa: E402

# mnemonic -> PPSSPP interpreter handler (from PPSSPP Core/MIPS/MIPSTables.cpp)
HANDLER = {}
for mn in ("addi", "addiu", "slti", "sltiu", "andi", "ori", "xori", "lui"):
    HANDLER[mn] = "Int_IType"
for mn in ("add", "addu", "sub", "subu", "and", "or", "xor", "nor", "slt", "sltu", "max", "min",
           "movz", "movn"):
    HANDLER[mn] = "Int_RType3"
for mn in ("lb", "lbu", "lh", "lhu", "lw", "lwl", "lwr", "sb", "sh", "sw", "swl", "swr"):
    HANDLER[mn] = "Int_ITypeMem"
for mn in ("ll", "sc"):
    HANDLER[mn] = "Int_StoreSync"
for mn in ("lwc1", "swc1"):
    HANDLER[mn] = "Int_FPULS"
for mn in ("mfc1", "cfc1", "mtc1", "ctc1"):
    HANDLER[mn] = "Int_mxc1"
for mn in ("clz", "clo"):
    HANDLER[mn] = "Int_RType2"
for mn in ("mult", "multu", "div", "divu", "madd", "maddu", "msub", "msubu", "mfhi", "mthi", "mflo",
           "mtlo"):
    HANDLER[mn] = "Int_MulDivType"
for mn in ("sll", "srl", "sra", "sllv", "srlv", "srav", "rotr", "rotrv"):
    HANDLER[mn] = "Int_ShiftType"
for mn in ("seb", "seh", "bitrev"):
    HANDLER[mn] = "Int_Allegrex"
for mn in ("wsbh", "wsbw"):
    HANDLER[mn] = "Int_Allegrex2"
for mn in ("ext", "ins"):
    HANDLER[mn] = "Int_Special3"
for mn in ("sqrt.s", "abs.s", "mov.s", "neg.s", "round.w.s", "trunc.w.s", "ceil.w.s", "floor.w.s",
           "cvt.w.s", "cvt.s.w"):
    HANDLER[mn] = "Int_FPU2op"
for mn in ("add.s", "sub.s", "mul.s", "div.s"):
    HANDLER[mn] = "Int_FPU3op"


def main(path, out):
    m = PspModule(open(path, "rb").read())
    funcs, starts = functions.discover(m)
    g = codegen.Gen(m, funcs, starts)
    seen = {}
    for r0, r1 in m.code_ranges:
        for a in range(r0, r1, 4):
            w = m.word(a - m.base)
            if w in seen:
                continue
            i = decode(w, a)
            h = HANDLER.get(i.mn)
            if i.mn.startswith("c.") and i.mn.endswith(".s"):
                h = "Int_FPUComp"
            if h:
                seen[w] = (i, h)
    with open(out, "w") as f:
        f.write("/* Generated by tools/recomp/gen_cpu_tests.py - do not distribute. */\n")
        f.write('#include "psp/recomp.h"\n\n')
        f.write("typedef void (*OpFn)(Ctx*);\n")
        for w, (i, h) in seen.items():
            f.write("static void t_%08x(Ctx* c) { %s }\n" % (w, g.op(i)))
        f.write("typedef struct { unsigned word; OpFn fn; const char* handler; const char* mn; } TestOp;\n")
        f.write("const TestOp g_test_ops[] = {\n")
        for w, (i, h) in seen.items():
            f.write('    {0x%08xu, t_%08x, "%s", "%s"},\n' % (w, w, h, i.mn))
        f.write("};\nconst unsigned g_test_op_count = %d;\n" % len(seen))
    print("%d distinct instruction words" % len(seen))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
